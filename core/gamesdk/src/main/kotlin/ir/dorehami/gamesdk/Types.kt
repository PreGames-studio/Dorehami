package ir.dorehami.gamesdk

/**
 * شناسهٔ نوع بازی (`"hokm"`، `"chess"`…). ثابت و کوچک؛ در رکورد بازی ذخیره می‌شود.
 */
@JvmInline
value class GameId(val value: String)

/**
 * شناسهٔ بازیکن در یک دست. در حالت آفلاین همان شناسهٔ دستگاه و در حالت آنلاین شناسهٔ حساب است؛
 * قواعد بازی فقط این رشته را می‌شناسد و به هیچ چیز دیگری وابسته نیست.
 */
@JvmInline
value class PlayerId(val value: String)

/** مرحلهٔ نشست بازی. */
enum class Phase {
    /** در حال آماده‌سازی: هنوز همه چیزِ لازم برای شروعِ بازی معلوم نشده (مثلاً حکم تعیین نشده). */
    SETUP,

    /** بازی در جریان است. */
    PLAYING,

    /** بازی تمام شده و `result()` مقدار دارد. */
    FINISHED,
}

/**
 * قابلیت‌هایی که یک بازی اعلام می‌کند. نام‌ها دقیقاً همین رشته‌ها هستند و در JSONِ رجیستری و
 * پاسخِ `GET /v1/games` سرور با همین کلیدها می‌روند.
 */
enum class Capability {
    /** اتاق بلوتوثی/وای‌فای دایرکت (بدون اینترنت). */
    BLUETOOTH_OFFLINE,

    /** اتاق آنلاین با کد روی سرور خودمان. */
    ONLINE,

    /** صف حریف تصادفی. */
    RANDOM_MATCH,

    /** پر کردن صندلی‌های خالی با ربات. */
    BOTS,

    /** چند نفر با یک گوشی (نوبت‌گردشی روی یک دستگاه). */
    PASS_AND_PLAY,

    /** تماشاچیِ بدون دست. */
    SPECTATORS,
    ;

    /** نام ثابتِ قابلیت برای خروجی JSON. */
    val key: String
        get() = name.lowercase()
}
